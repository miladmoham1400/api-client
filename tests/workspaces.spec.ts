import { launchDesktop } from './fixtures/desktop'
import { shutdown } from './fixtures/shutdown'
import { mkdtempSync, rmSync } from 'node:fs'
import { tmpdir } from 'node:os'
import { join } from 'node:path'
import { expect, test } from '@playwright/test'

test('workspace CRUD and selection persist across restart; confirmation and failed writes retain data', async () => {
  const directory = mkdtempSync(join(tmpdir(), 'api-client-workspace-ui-'))
  const env = { ...Object.fromEntries(Object.entries(process.env).filter((entry): entry is [string, string] => entry[1] !== undefined && !['ELECTRON_RUN_AS_NODE', 'ELECTRON_RENDERER_URL'].includes(entry[0]))), XDG_CONFIG_HOME: directory, APPDATA: directory }
  let application = await launchDesktop({ args: ['.'], chromiumSandbox: true, env })
  try {
    let page = await application.firstWindow()
    const sidebar = () => page.getByRole('complementary', { name: 'Collections and requests' })
    const create = async (name: string) => {
      await sidebar().getByRole('button', { name: 'Create Workspace', exact: true }).click()
      const dialog = page.getByRole('dialog', { name: 'Create workspace', exact: true })
      await expect(dialog.getByLabel('Workspace name')).toBeFocused()
      await dialog.getByLabel('Workspace name').fill(name)
      await dialog.getByRole('button', { name: 'Create workspace', exact: true }).click()
      await expect(dialog).not.toBeVisible()
    }
    const openMenu = async (action: string) => {
      await page.getByRole('button', { name: 'Workspace menu' }).click()
      await page.getByRole('menuitem', { name: action, exact: true }).click()
    }
    await expect(sidebar().getByText('No workspace selected', { exact: true })).toBeVisible()
    expect(await page.evaluate(() => Reflect.apply(window.offlineApi.workspaces.create, null, [{ name: 'Invalid shape' }]))).toMatchObject({ ok: false, error: { code: 'VALIDATION' } })
    expect(await page.evaluate(() => window.offlineApi.workspaces.list())).toEqual({ ok: true, data: { workspaces: [], selectedWorkspaceId: null } })
    await sidebar().getByRole('button', { name: 'Create Workspace', exact: true }).click()
    let dialog = page.getByRole('dialog', { name: 'Create workspace', exact: true })
    await dialog.getByLabel('Workspace name').fill('   ')
    await dialog.getByRole('button', { name: 'Create workspace', exact: true }).click()
    await expect(dialog.getByRole('alert')).toContainText('1–100')
    await dialog.getByLabel('Workspace name').fill('x'.repeat(101))
    await dialog.getByRole('button', { name: 'Create workspace', exact: true }).click()
    await expect(dialog.getByRole('alert')).toContainText('1–100')
    await page.keyboard.press('Escape')
    await expect(sidebar().getByRole('button', { name: 'Create Workspace', exact: true })).toBeFocused()
    await create('  Clinic API  ')
    await expect(sidebar().getByText('Clinic API', { exact: true })).toBeVisible()
    await create('Second project')
    const snapshot = await page.evaluate(() => window.offlineApi.workspaces.list())
    if (!snapshot.ok) throw new Error('Failed to list workspaces')
    const a = snapshot.data.workspaces.find(workspace => workspace.name === 'Clinic API')?.id
    const b = snapshot.data.workspaces.find(workspace => workspace.name === 'Second project')?.id
    if (!a || !b) throw new Error('Missing workspace IDs')
    await page.getByLabel('Workspace', { exact: true }).selectOption(a)
    await expect(sidebar().getByText('Clinic API', { exact: true })).toBeVisible()
    await expect(sidebar().getByText('Second project', { exact: true })).toHaveCount(0)
    await openMenu('Rename workspace')
    dialog = page.getByRole('dialog', { name: 'Rename workspace', exact: true })
    await dialog.getByLabel('Workspace name').fill('Clinic API renamed')
    await dialog.getByRole('button', { name: 'Save name', exact: true }).click()
    await expect(dialog).not.toBeVisible()
    await expect(sidebar().getByText('Clinic API renamed', { exact: true })).toBeVisible()
    // Real SQLite trigger rejects a rename: the dialog/draft and saved view survive.
    await application.evaluate(({ app }) => {
      const load = process.getBuiltinModule('module').createRequire(`${app.getAppPath()}/package.json`)
      const Driver: typeof import('better-sqlite3') = load('better-sqlite3')
      const db = new Driver(`${app.getPath('userData')}/offline-api-client.sqlite`)
      try { db.exec("CREATE TRIGGER fail_workspace_rename BEFORE UPDATE ON workspaces WHEN NEW.name='Rejected rename' BEGIN SELECT RAISE(ABORT,'synthetic private detail'); END;") } finally { db.close() }
    })
    await openMenu('Rename workspace')
    dialog = page.getByRole('dialog', { name: 'Rename workspace', exact: true })
    await dialog.getByLabel('Workspace name').fill('Rejected rename')
    await dialog.getByRole('button', { name: 'Save name', exact: true }).click()
    await expect(dialog.getByRole('alert')).toContainText('could not be loaded or saved')
    await expect(dialog.getByLabel('Workspace name')).toHaveValue('Rejected rename')
    const afterFailure = await page.evaluate(() => window.offlineApi.workspaces.list())
    expect(afterFailure.ok && afterFailure.data.workspaces.find(workspace => workspace.id === a)?.name).toBe('Clinic API renamed')
    await expect(page.getByText('synthetic private detail')).toHaveCount(0)
    await dialog.getByRole('button', { name: 'Cancel', exact: true }).click()
    await expect(sidebar().getByText('Clinic API renamed', { exact: true })).toBeVisible()
    await application.close()
    application = await launchDesktop({ args: ['.'], chromiumSandbox: true, env })
    page = await application.firstWindow()
    await expect(page.getByLabel('Workspace', { exact: true })).toHaveValue(a)
    await expect(sidebar().getByText('Clinic API renamed', { exact: true })).toBeVisible()
    await expect(page.getByLabel('Workspace', { exact: true }).locator('option')).toHaveCount(3)
    await openMenu('Delete workspace')
    dialog = page.getByRole('dialog', { name: 'Delete workspace', exact: true })
    await expect(dialog).toContainText('collections, requests, environments, variables and stored secrets')
    await expect(dialog.getByRole('button', { name: 'Cancel', exact: true })).toBeFocused()
    await dialog.getByRole('button', { name: 'Cancel', exact: true }).click()
    await expect(page.getByLabel('Workspace', { exact: true })).toHaveValue(a)
    await openMenu('Delete workspace')
    await dialog.getByRole('button', { name: 'Delete permanently', exact: true }).click()
    await expect(dialog).not.toBeVisible()
    await expect(page.getByLabel('Workspace', { exact: true })).toHaveValue('')
    await expect(page.getByLabel('Workspace', { exact: true })).toBeFocused()
    await expect(sidebar().getByText('No workspace selected', { exact: true })).toBeVisible()
    await page.getByLabel('Workspace', { exact: true }).selectOption(b)
    await expect(sidebar().getByText('Second project', { exact: true })).toBeVisible()
    await expect(sidebar().getByText('Clinic API renamed', { exact: true })).toHaveCount(0)
    await expect(page.locator('[role="dialog"]:visible')).toHaveCount(0)
    await page.screenshot({ path: '/tmp/api-client-workspaces.png' })
    await application.close()
    application = await launchDesktop({ args: ['.'], chromiumSandbox: true, env })
    page = await application.firstWindow()
    await expect(page.getByLabel('Workspace', { exact: true })).toHaveValue(b)
    await expect(page.getByLabel('Workspace', { exact: true }).locator('option')).toHaveCount(2)
    await openMenu('Delete workspace')
    await page.getByRole('dialog', { name: 'Delete workspace', exact: true }).getByRole('button', { name: 'Delete permanently', exact: true }).click()
    await expect(page.getByLabel('Workspace', { exact: true })).toHaveValue('')
    await application.close()
    application = await launchDesktop({ args: ['.'], chromiumSandbox: true, env })
    page = await application.firstWindow()
    await expect(sidebar().getByText('No workspace selected', { exact: true })).toBeVisible()
    expect(await page.evaluate(() => window.offlineApi.workspaces.list())).toEqual({ ok: true, data: { workspaces: [], selectedWorkspaceId: null } })
    await expect(page.getByRole('button', { name: 'Send', exact: true })).toBeDisabled()
    const resources = await page.evaluate(() => performance.getEntriesByType('resource').map(entry => entry.name))
    expect(resources.every(url => url.startsWith('file:') || url.startsWith('data:'))).toBe(true)
  } finally { await shutdown(application); rmSync(directory, { recursive: true, force: true }) }
})
