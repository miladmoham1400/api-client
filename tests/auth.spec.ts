import { shutdown } from './fixtures/shutdown'
import { mkdtempSync, rmSync } from 'node:fs'
import { tmpdir } from 'node:os'
import { join } from 'node:path'
import { _electron, expect, test } from '@playwright/test'

test('auth editing saves literal handles, templates, replacements and missing session state without enabling Send', async () => {
  const directory = mkdtempSync(join(tmpdir(), 'api-client-auth-ui-'))
  const env = { ...Object.fromEntries(Object.entries(process.env).filter((entry): entry is [string, string] => entry[1] !== undefined && !['ELECTRON_RUN_AS_NODE', 'ELECTRON_RENDERER_URL'].includes(entry[0]))), XDG_CONFIG_HOME: directory, APPDATA: directory }
  let application = await _electron.launch({ args: ['.'], chromiumSandbox: true, env })
  try {
    let page = await application.firstWindow()
    await page.getByRole('button', { name: 'Create Workspace', exact: true }).click()
    const dialog = page.getByRole('dialog', { name: 'Create workspace', exact: true })
    await dialog.getByLabel('Workspace name').fill('Auth workspace')
    await dialog.getByRole('button', { name: 'Create workspace', exact: true }).click()
    await expect(dialog).not.toBeVisible()
    await page.getByRole('button', { name: 'Create Request', exact: true }).click()
    await page.getByLabel('Request name', { exact: true }).fill('Auth')
    await page.getByRole('tab', { name: 'Auth', exact: true }).click()
    await expect(page.getByLabel('Auth mode', { exact: true })).toHaveValue('none')
    await page.getByLabel('Auth mode', { exact: true }).selectOption('basic')
    await page.getByLabel('Basic username', { exact: true }).fill('synthetic-user')
    await page.getByLabel('Basic password', { exact: true }).fill('synthetic-password')
    await expect(page.getByLabel('Basic password', { exact: true })).toHaveAttribute('type', 'password')
    await page.keyboard.press('Control+s')
    await expect(page.getByRole('status').filter({ hasText: /^Saved$/ })).toBeVisible()
    await expect(page.getByLabel('Basic username', { exact: true })).toHaveValue('')
    await expect(page.getByLabel('Basic password', { exact: true })).toHaveValue('')
    const w = await page.getByLabel('Workspace', { exact: true }).inputValue()
    const snapshot = await page.evaluate(workspace => window.offlineApi.requests.list(workspace), w)
    expect(JSON.stringify(snapshot)).not.toContain('synthetic-password'); expect(JSON.stringify(snapshot)).not.toContain('secretId')
    expect(snapshot.ok && snapshot.data.editor?.auth).toMatchObject({ mode: 'basic', password: { kind: 'stored', hasValue: true } })
    await page.getByLabel('Request name', { exact: true }).fill('Renamed')
    await page.keyboard.press('Control+s')
    await expect(page.getByRole('status').filter({ hasText: /^Saved$/ })).toBeVisible()
    await application.close()
    application = await _electron.launch({ args: ['.'], chromiumSandbox: true, env })
    page = await application.firstWindow()
    await page.getByRole('tab', { name: 'Auth', exact: true }).click()
    await expect(page.getByLabel('Auth mode', { exact: true })).toHaveValue('basic')
    const reopened = await page.evaluate(workspace => window.offlineApi.requests.list(workspace), w)
    if (!reopened.ok || !reopened.data.editor) throw new Error('Missing editor')
    if (reopened.data.editor.credentialStorage === 'session') await expect(page.getByText('Missing stored credential: re-enter it.', { exact: true })).toBeVisible()
    await page.getByLabel('Basic password', { exact: true }).fill('synthetic-replacement')
    await page.keyboard.press('Control+s')
    await expect(page.getByRole('status').filter({ hasText: /^Saved$/ })).toBeVisible()
    await page.getByLabel('Auth mode', { exact: true }).selectOption('bearer')
    await page.getByLabel('Bearer token', { exact: true }).fill('{{fixture}}')
    await page.keyboard.press('Control+s')
    await expect(page.getByRole('status').filter({ hasText: /^Saved$/ })).toBeVisible()
    await expect(page.getByLabel('Bearer token', { exact: true })).toHaveValue('{{fixture}}')
    await expect(page.getByText('Session only: re-enter after restart', { exact: true })).not.toBeVisible()
    await page.screenshot({ path: '/tmp/api-client-auth.png' })
    await page.getByLabel('Auth mode', { exact: true }).selectOption('none')
    await page.keyboard.press('Control+s')
    await expect(page.getByRole('status').filter({ hasText: /^Saved$/ })).toBeVisible()
    await expect(page.getByRole('button', { name: 'Send', exact: true })).toBeDisabled()
  } finally { await shutdown(application); rmSync(directory, { recursive: true, force: true }) }
})
