import { expect, test } from '@playwright/test'
import { mkdtempSync, rmSync, writeFileSync } from 'node:fs'
import { tmpdir } from 'node:os'
import { join } from 'node:path'
import { launchDesktop } from './fixtures/desktop'
import { shutdown } from './fixtures/shutdown'
import { startFixture } from './fixtures/http'

const environment = (directory: string) => ({ ...Object.fromEntries(Object.entries(process.env).filter((e): e is [string, string] => e[1] !== undefined && !['ELECTRON_RUN_AS_NODE', 'ELECTRON_RENDERER_URL'].includes(e[0]))), XDG_CONFIG_HOME: directory, APPDATA: directory })

test('request tabs select exact saved APIs, retain bodies/auth/uploads and responses, close without deletion and match corners', async () => {
  test.setTimeout(60000)
  const directory = mkdtempSync(join(tmpdir(), 'request-tabs-')), received: { url: string | undefined; body: string }[] = []
  const fixture = await startFixture(false, (req, res) => { let body = ''; req.setEncoding('utf8'); req.on('data', (chunk: string) => { body += chunk }); req.on('end', () => { received.push({ url: req.url, body }); res.writeHead(200, { 'Content-Type': 'application/json' }); res.end(JSON.stringify({ route: req.url })) }) })
  const app = await launchDesktop({ args: ['.'], chromiumSandbox: true, env: environment(directory) })
  try {
    const page = await app.firstWindow()
    const ids = await page.evaluate(async url => {
      const api = window.offlineApi, created = await api.workspaces.create('Tabs')
      if (!created.ok || !created.data.selectedWorkspaceId) throw new Error('Workspace missing')
      const w = created.data.selectedWorkspaceId
      const a = await api.requests.create(w, { name: 'Alpha', method: 'POST', urlTemplate: url + '/alpha', collectionId: null, body: { kind: 'json', text: '{"case":1}' } })
      const b = await api.requests.create(w, { name: 'Beta', method: 'GET', urlTemplate: url + '/beta', collectionId: null })
      if (!a.ok || !b.ok) throw new Error('Requests missing')
      await api.requests.get(w, a.data.editor!.id)
      return { w, a: a.data.editor!.id, b: b.data.editor!.id }
    }, fixture.url)
    await page.reload()
    const editor = page.getByRole('region', { name: 'Request editor', exact: true }), response = page.getByRole('region', { name: 'Response', exact: true })
    const tabs = page.getByRole('tablist', { name: 'Open requests', exact: true })
    await expect(tabs.getByRole('tab', { name: 'POST Alpha', exact: true })).toHaveAttribute('aria-selected', 'true')
    await page.getByRole('button', { name: 'Beta', exact: true }).click()
    await expect(tabs.getByRole('tab')).toHaveCount(2)
    await tabs.getByRole('tab', { name: 'POST Alpha', exact: true }).click()
    await editor.getByRole('tab', { name: 'Body', exact: true }).click()
    await page.getByLabel('JSON source text', { exact: true }).fill('{"case":2}')
    await tabs.getByRole('tab', { name: 'GET Beta', exact: true }).click() // flushes pending blur format/autosave
    await expect(page.getByLabel('Request name', { exact: true })).toHaveValue('Beta')
    await tabs.getByRole('tab', { name: 'POST Alpha', exact: true }).click()
    await expect(page.getByLabel('JSON source text', { exact: true })).toHaveValue('{\n  "case": 2\n}')
    await editor.getByRole('tab', { name: 'Auth', exact: true }).click()
    await page.getByLabel('Auth mode').selectOption('bearer')
    await page.getByLabel('Bearer token').fill('synthetic-tab-token')
    await tabs.getByRole('tab', { name: 'GET Beta', exact: true }).click()
    await tabs.getByRole('tab', { name: 'POST Alpha', exact: true }).click()
    await expect(page.getByLabel('Bearer token')).toHaveValue('synthetic-tab-token')
    await page.getByRole('button', { name: 'Send', exact: true }).click()
    await expect(response.getByLabel('Response body JSON')).toContainText('/alpha')
    await tabs.getByRole('tab', { name: 'GET Beta', exact: true }).click()
    await expect(response.getByLabel('Response body JSON')).not.toBeVisible()
    await page.getByRole('button', { name: 'Send', exact: true }).click()
    await expect(response.getByLabel('Response body JSON')).toContainText('/beta')
    await tabs.getByRole('tab', { name: 'POST Alpha', exact: true }).click()
    await expect(response.getByLabel('Response body JSON')).toContainText('/alpha')
    expect(received.map(r => r.url)).toEqual(['/alpha', '/beta'])
    expect(JSON.parse(received[0]!.body) as unknown).toEqual({ case: 2 })
    await editor.getByRole('tab', { name: 'Body', exact: true }).click()
    for (const theme of ['dark', 'light']) {
      await page.getByLabel('Theme', { exact: true }).selectOption(theme)
      const radii = await page.evaluate(() => ['.editor-panel', '.response-panel', '.json-editor', '.json-editor-input'].map(selector => getComputedStyle(document.querySelector(selector)!).borderTopLeftRadius))
      expect(new Set(radii).size).toBe(1)
      await page.screenshot({ path: `/tmp/api-client-request-tabs-${theme}.png`, animations: 'disabled' })
    }
    await tabs.getByRole('tab', { name: 'POST Alpha', exact: true }).focus()
    await page.keyboard.press('ArrowRight'); await page.keyboard.press('Enter')
    await expect(page.getByLabel('Request name', { exact: true })).toHaveValue('Beta')
    await tabs.getByRole('button', { name: 'Close GET Beta', exact: true }).click()
    await expect(page.getByLabel('Request name', { exact: true })).toHaveValue('Alpha')
    await expect(tabs.getByRole('tab')).toHaveCount(1)
    await page.getByRole('button', { name: 'Beta', exact: true }).click()
    await expect(tabs.getByRole('tab')).toHaveCount(2)
    await expect(response.getByLabel('Response body JSON')).not.toBeVisible() // closed tab drops its response
    await tabs.getByRole('button', { name: 'Close POST Alpha', exact: true }).click()
    await tabs.getByRole('button', { name: 'Close GET Beta', exact: true }).click()
    await expect(tabs.getByRole('tab')).toHaveCount(0)
    await expect(page.getByRole('heading', { name: 'No request selected' })).toBeVisible()
    const saved = await page.evaluate(w => window.offlineApi.requests.list(w), ids.w)
    expect(saved.ok && saved.data.requests.length).toBe(2)
    expect(received).toHaveLength(2)
    // A selected local file remains a live capability when switching tabs.
    const upload = join(directory, 'synthetic-upload.txt'); writeFileSync(upload, 'tab-upload-content')
    await app.evaluate(({ dialog }, path) => { dialog.showOpenDialog = async () => ({ canceled: false, filePaths: [path] }) }, upload)
    await page.getByRole('button', { name: 'Alpha', exact: true }).click()
    await page.getByLabel('Body mode', { exact: true }).selectOption('multipart')
    await page.getByRole('button', { name: 'Add multipart file', exact: true }).click()
    await page.getByLabel('Multipart 1 key', { exact: true }).fill('upload')
    await page.getByRole('button', { name: 'Choose multipart 1 file', exact: true }).click()
    await page.getByRole('button', { name: 'Beta', exact: true }).click()
    await tabs.getByRole('tab', { name: 'POST Alpha', exact: true }).click()
    await page.getByRole('button', { name: 'Send', exact: true }).click()
    await expect.poll(() => received.length).toBe(3)
    expect(received[2]!.body).toContain('tab-upload-content')
    await page.getByRole('button', { name: 'Actions for request: Beta', exact: true }).click()
    await page.getByRole('menuitem', { name: 'Delete request', exact: true }).click()
    await page.getByRole('dialog', { name: 'Delete request', exact: true }).getByRole('button', { name: 'Delete request', exact: true }).click()
    await expect(tabs.getByRole('tab')).toHaveCount(1)
    await expect(tabs.getByRole('tab', { name: 'POST Alpha', exact: true })).toHaveAttribute('aria-selected', 'true')
    // Switching workspace clears tabs and response snapshots, and never sends.
    await page.evaluate(() => window.offlineApi.workspaces.create('Other'))
    await page.reload()
    await expect(tabs.getByRole('tab')).toHaveCount(0)
    expect(received).toHaveLength(3)
  } finally { await shutdown(app); await fixture.close(); rmSync(directory, { recursive: true, force: true }) }
})

test('tab navigation and closing guard invalid drafts and active sends, and workspace changes isolate tabs', async () => {
  test.setTimeout(60000)
  const directory = mkdtempSync(join(tmpdir(), 'request-tab-guards-')), calls: string[] = []
  const fixture = await startFixture(false, (req, res) => {
    calls.push(req.url ?? '')
    if (req.url === '/slow') { const timer = setTimeout(() => res.end('late'), 25000); res.on('close', () => clearTimeout(timer)) }
    else res.end('fast')
  })
  const app = await launchDesktop({ args: ['.'], chromiumSandbox: true, env: environment(directory) })
  try {
    const page = await app.firstWindow()
    await page.evaluate(async url => {
      const api = window.offlineApi, result = await api.workspaces.create('Guard tabs')
      if (!result.ok || !result.data.selectedWorkspaceId) throw new Error('No workspace')
      const w = result.data.selectedWorkspaceId
      await api.requests.create(w, { name: 'Slow', method: 'GET', urlTemplate: url + '/slow', collectionId: null })
      await api.requests.create(w, { name: 'Fast', method: 'GET', urlTemplate: url + '/fast', collectionId: null })
    }, fixture.url)
    await page.reload()
    const tabs = page.getByRole('tablist', { name: 'Open requests', exact: true }), editor = page.getByRole('region', { name: 'Request editor', exact: true })
    await page.getByRole('button', { name: 'Slow', exact: true }).click()
    await expect(tabs.getByRole('tab')).toHaveCount(2)
    await page.getByLabel('Request name', { exact: true }).fill('')
    await tabs.getByRole('tab', { name: 'GET Fast', exact: true }).click()
    const dirty = page.getByRole('dialog', { name: 'Unsaved request changes', exact: true })
    await expect(dirty).toBeVisible()
    await dirty.getByRole('button', { name: 'Cancel', exact: true }).click()
    await expect(tabs.getByRole('tab', { name: 'GET Slow', exact: true })).toHaveAttribute('aria-selected', 'true')
    await expect(page.getByLabel('Request name', { exact: true })).toHaveValue('')
    await tabs.getByRole('button', { name: 'Close GET Slow', exact: true }).click()
    await dirty.getByRole('button', { name: 'Discard', exact: true }).click()
    await expect(page.getByLabel('Request name', { exact: true })).toHaveValue('Fast')
    await expect(tabs.getByRole('tab')).toHaveCount(1)
    expect(calls).toHaveLength(0)
    await page.getByRole('button', { name: 'Slow', exact: true }).click()
    await page.getByRole('button', { name: 'Send', exact: true }).click()
    await expect.poll(() => calls.length).toBe(1)
    await tabs.getByRole('tab', { name: 'GET Fast', exact: true }).click()
    const active = page.getByRole('dialog', { name: 'Request in progress', exact: true })
    await active.getByRole('button', { name: 'Stay', exact: true }).click()
    await expect(page.getByRole('dialog')).not.toBeVisible()
    await expect(tabs.getByRole('tab', { name: 'GET Slow', exact: true })).toHaveAttribute('aria-selected', 'true')
    await tabs.getByRole('tab', { name: 'GET Slow', exact: true }).focus()
    await page.keyboard.press('ArrowLeft')
    await expect(tabs.getByRole('tab', { name: 'GET Fast', exact: true })).toBeFocused()
    await page.keyboard.press('Delete') // closes focused inactive tab without cancelling the active send
    await expect(editor.getByRole('button', { name: 'Cancel', exact: true })).toBeEnabled()
    await expect(tabs.getByRole('tab')).toHaveCount(1)
    await tabs.getByRole('button', { name: 'Close GET Slow', exact: true }).click()
    await active.getByRole('button', { name: 'Cancel request', exact: true }).click()
    await expect(page.getByRole('heading', { name: 'No request selected' })).toBeVisible()
    await expect(tabs.getByRole('tab')).toHaveCount(0)
    expect(calls).toEqual(['/slow'])
    await page.getByRole('button', { name: 'Create Request', exact: true }).click()
    await page.getByLabel('Request name', { exact: true }).fill('')
    await tabs.getByRole('button', { name: 'Close new request', exact: true }).click()
    await dirty.getByRole('button', { name: 'Discard', exact: true }).click()
    await expect(page.getByRole('heading', { name: 'No request selected' })).toBeVisible()
    await expect(tabs.getByRole('tab')).toHaveCount(0)
    await page.getByRole('button', { name: 'Fast', exact: true }).click()
    await page.getByRole('button', { name: 'Send', exact: true }).click()
    await expect(editor.getByRole('status')).toContainText(['Saved', 'Request completed'])
    await page.getByRole('button', { name: 'Create Workspace', exact: true }).click()
    const create = page.getByRole('dialog', { name: 'Create workspace', exact: true })
    await create.getByLabel('Workspace name').fill('Isolated tabs')
    await create.getByRole('button', { name: 'Create workspace', exact: true }).click()
    await expect(tabs.getByRole('tab')).toHaveCount(0)
    await expect(page.getByRole('region', { name: 'Response', exact: true }).getByLabel('Response body text')).not.toBeVisible()
    expect(calls).toEqual(['/slow', '/fast'])
  } finally { await shutdown(app); await fixture.close(); rmSync(directory, { recursive: true, force: true }) }
})
