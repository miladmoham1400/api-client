import { expect, test } from '@playwright/test'
import { mkdtempSync, rmSync } from 'node:fs'
import { tmpdir } from 'node:os'
import { join } from 'node:path'
import { launchDesktop } from './fixtures/desktop'
import { shutdown } from './fixtures/shutdown'

test('active Bearer survives autosave, templates complete, JSON diagnostics and library controls stay usable', async () => {
  test.setTimeout(60000)
  const directory = mkdtempSync(join(tmpdir(), 'interface-fixes-'))
  const env = { ...Object.fromEntries(Object.entries(process.env).filter((e): e is [string, string] => e[1] !== undefined && !['ELECTRON_RUN_AS_NODE', 'ELECTRON_RENDERER_URL'].includes(e[0]))), XDG_CONFIG_HOME: directory, APPDATA: directory }
  const app = await launchDesktop({ args: ['.'], chromiumSandbox: true, env })
  try {
    const page = await app.firstWindow()
    await page.evaluate(async () => {
      const api = window.offlineApi, created = await api.workspaces.create('Polish')
      if (!created.ok || !created.data.selectedWorkspaceId) throw new Error('No workspace')
      const w = created.data.selectedWorkspaceId, collection = await api.collections.create(w, 'Local')
      if (!collection.ok) throw new Error('No collection')
      const c = collection.data.collections[0]!.id, folder = await api.folders.create(w, c, null, 'Users')
      if (!folder.ok) throw new Error('No folder')
      await api.variables.upsert(w, null, 'token', 'synthetic-variable', true)
      await api.requests.create(w, { name: 'Nested request', collectionId: c, folderId: folder.data.folders[0]!.id, method: 'POST', urlTemplate: 'http://localhost:9', body: { kind: 'json', text: '{"valid":true}' } })
    })
    await page.reload()
    const editor = page.getByRole('region', { name: 'Request editor', exact: true })
    await expect(page.getByLabel('Request name', { exact: true })).toHaveValue('Nested request')
    await editor.getByRole('tab', { name: 'Auth', exact: true }).click()
    await page.getByLabel('Auth mode', { exact: true }).selectOption('bearer')
    const token = page.getByLabel('Bearer token', { exact: true })
    await token.fill('synthetic-visible-token')
    await expect(editor.getByRole('status')).toHaveText('Saved')
    await expect(token).toHaveValue('synthetic-visible-token')
    await expect(token).toHaveAttribute('type', 'text')
    await page.getByLabel('Request name', { exact: true }).fill('Renamed request')
    await expect(editor.getByRole('status')).toHaveText('Saved')
    await expect(token).toHaveValue('synthetic-visible-token')
    await token.fill('{{to'); await token.press('End')
    await expect(page.getByRole('listbox', { name: 'Variable suggestions' })).toBeVisible()
    await token.press('Tab')
    await expect(token).toHaveValue('{{token}}')
    await expect(editor.getByRole('status')).toHaveText('Saved')
    await editor.getByRole('tab', { name: 'Body', exact: true }).click()
    const body = page.getByLabel('JSON source text', { exact: true })
    await body.fill('{\n  "valid": true\n  "missingComma": 1\n}')
    await page.getByLabel('Request name', { exact: true }).click()
    const error = page.locator('#body-syntax-error')
    await expect(error).toContainText('Line 3')
    const positions = await page.evaluate(() => ({ body: document.querySelector('#body-text')!.getBoundingClientRect().bottom, error: document.querySelector('#body-syntax-error')!.getBoundingClientRect().top, details: [...document.querySelectorAll('summary')].find(e => e.textContent === 'Body details')!.getBoundingClientRect().top }))
    expect(positions.error).toBeGreaterThanOrEqual(positions.body)
    expect(positions.details).toBeGreaterThan(positions.error)
    await expect(page.locator('.json-editor').filter({ has: body }).locator('.json-line-numbers')).toHaveText('1\n2\n3\n4')
    await body.fill(Array.from({ length: 80 }, (_, i) => i === 0 ? '{' : i === 79 ? '}' : `"field${i}": ${i}${i === 78 ? '' : ','}`).join('\n'))
    await body.evaluate(element => { element.scrollTop = 200; element.dispatchEvent(new Event('scroll')) })
    expect(await page.locator('.json-editor').filter({ has: body }).locator('.json-line-numbers').evaluate(element => element.scrollTop)).toBeGreaterThan(0)
    await page.getByLabel('Request name', { exact: true }).click()
    await expect(error).not.toBeVisible()
    const about = page.getByRole('button', { name: 'About this shell', exact: true })
    await about.hover()
    await expect(page.getByRole('tooltip')).toHaveText('About')
    await page.screenshot({ path: '/tmp/api-client-interface-fixes-dark.png', animations: 'disabled' })
    await page.keyboard.press('Escape')
    await expect(page.getByRole('tooltip')).not.toBeVisible()
    await about.focus()
    await expect(page.getByRole('tooltip')).toHaveText('About')
    await page.keyboard.press('Tab')
    const requestRow = page.getByRole('treeitem', { name: 'POST request: Renamed request', exact: true })
    await requestRow.getByRole('button', { name: 'Renamed request', exact: true }).hover()
    await expect(requestRow.locator('button').first()).toHaveCSS('background-color', 'rgba(0, 0, 0, 0)')
    expect((await requestRow.boundingBox())!.height).toBeLessThanOrEqual(30)
    const folderMenu = page.getByRole('button', { name: 'Actions for folder: Users', exact: true })
    await folderMenu.click()
    await page.getByRole('menuitem', { name: 'Duplicate folder', exact: true }).click()
    await expect(page.getByRole('treeitem', { name: 'folder: Users (copy)', exact: true })).toBeVisible()
    await expect(page.getByLabel('Request name', { exact: true })).toHaveValue('Renamed request')
    const snapshot = await page.evaluate(async () => {
      const api = window.offlineApi, w = await api.workspaces.list()
      if (!w.ok || !w.data.selectedWorkspaceId) throw new Error('No workspace')
      return api.requests.list(w.data.selectedWorkspaceId)
    })
    expect(snapshot.ok && snapshot.data.requests).toHaveLength(2)
    expect(await page.content()).not.toContain('synthetic-variable')
    await app.evaluate(({ dialog }) => { dialog.showOpenDialog = async () => ({ canceled: true, filePaths: [] }) })
    await page.getByRole('button', { name: 'Import collection or workspace', exact: true }).click()
    const importing = page.getByRole('dialog', { name: 'Import collection or workspace', exact: true })
    await importing.getByRole('button', { name: 'Choose JSON file', exact: true }).click()
    await expect(importing).not.toBeVisible()
    await expect(page.getByText('Import cancelled.', { exact: true })).not.toBeVisible()
    await page.getByLabel('Theme', { exact: true }).selectOption('light')
    await about.hover()
    await expect(page.getByRole('tooltip')).toHaveText('About')
    await page.screenshot({ path: '/tmp/api-client-interface-fixes-light.png', animations: 'disabled' })
  } finally { await shutdown(app); rmSync(directory, { recursive: true, force: true }) }
})
