import { mkdtempSync, rmSync } from 'node:fs'
import { tmpdir } from 'node:os'
import { join } from 'node:path'
import { _electron, expect, test } from '@playwright/test'

test('body modes retain inactive drafts while Save/restart persists only the active source', async () => {
  const directory = mkdtempSync(join(tmpdir(), 'api-client-body-ui-'))
  const env = { ...Object.fromEntries(Object.entries(process.env).filter((entry): entry is [string, string] => entry[1] !== undefined && !['ELECTRON_RUN_AS_NODE', 'ELECTRON_RENDERER_URL'].includes(entry[0]))), XDG_CONFIG_HOME: directory, APPDATA: directory }
  let application = await _electron.launch({ args: ['.'], chromiumSandbox: true, env })
  try {
    let page = await application.firstWindow()
    await page.getByRole('button', { name: 'Create Workspace', exact: true }).click()
    const dialog = page.getByRole('dialog', { name: 'Create workspace', exact: true })
    await dialog.getByLabel('Workspace name').fill('Body workspace')
    await dialog.getByRole('button', { name: 'Create workspace', exact: true }).click()
    await expect(dialog).not.toBeVisible()
    await page.getByRole('button', { name: 'Create Request', exact: true }).click()
    await page.getByLabel('Request name', { exact: true }).fill('Body')
    await page.getByRole('tab', { name: 'Body', exact: true }).first().click()
    await expect(page.getByLabel('Body mode', { exact: true })).toHaveValue('none')
    await page.getByLabel('Body mode', { exact: true }).selectOption('json')
    await page.keyboard.press('Control+s')
    await expect(page.locator('#body-error')).toContainText('GET and HEAD')
    await page.getByLabel('HTTP method', { exact: true }).selectOption('POST')
    const source = ' {\n  "message": "سلام 🌍", "value": "{{value}}"\n}  '
    await page.getByLabel('JSON source text', { exact: true }).fill(source)
    await page.getByLabel('Body mode', { exact: true }).selectOption('raw')
    await page.getByLabel('Raw body text', { exact: true }).fill('سلام 🌍\n')
    await page.getByLabel('Raw media type', { exact: true }).fill('bad type')
    await page.keyboard.press('Control+s')
    await expect(page.locator('[id="body.mediaType-error"]')).toContainText('valid media type')
    await page.getByLabel('Raw media type', { exact: true }).fill('text/plain; charset=utf-8')
    await page.getByLabel('Body mode', { exact: true }).selectOption('json')
    await expect(page.getByLabel('JSON source text', { exact: true })).toHaveValue(source)
    await page.keyboard.press('Control+s')
    await expect(page.getByRole('status').filter({ hasText: /^Saved$/ })).toBeVisible()
    const workspace = await page.evaluate(() => window.offlineApi.workspaces.list())
    if (!workspace.ok || !workspace.data.selectedWorkspaceId) throw new Error('Missing workspace')
    const id = workspace.data.selectedWorkspaceId
    const saved = await page.evaluate(workspace => window.offlineApi.requests.list(workspace), id)
    expect(saved.ok && saved.data.editor?.body).toEqual({ kind: 'json', text: source })
    await page.getByLabel('Body mode', { exact: true }).selectOption('raw')
    await expect(page.getByLabel('Raw body text', { exact: true })).toHaveValue('سلام 🌍\n')
    await expect(page.getByLabel('Raw media type', { exact: true })).toHaveValue('text/plain; charset=utf-8')
    await page.keyboard.press('Control+s')
    await expect(page.getByRole('status').filter({ hasText: /^Saved$/ })).toBeVisible()
    await application.close()
    application = await _electron.launch({ args: ['.'], chromiumSandbox: true, env })
    page = await application.firstWindow()
    await page.getByRole('tab', { name: 'Body', exact: true }).first().click()
    await expect(page.getByLabel('Raw body text', { exact: true })).toHaveValue('سلام 🌍\n')
    await page.getByLabel('Body mode', { exact: true }).selectOption('json')
    await expect(page.getByLabel('JSON source text', { exact: true })).toHaveValue('')
    await page.keyboard.press('Control+s')
    await expect(page.getByRole('status').filter({ hasText: /^Saved$/ })).toBeVisible()
    const empty = await page.evaluate(workspace => window.offlineApi.requests.list(workspace), id)
    expect(empty.ok && empty.data.editor?.body).toEqual({ kind: 'json', text: '' })
    await page.getByLabel('Body mode', { exact: true }).selectOption('none')
    await page.keyboard.press('Control+s')
    await expect(page.getByRole('status').filter({ hasText: /^Saved$/ })).toBeVisible()
    const none = await page.evaluate(workspace => window.offlineApi.requests.list(workspace), id)
    expect(none.ok && none.data.editor?.body).toEqual({ kind: 'none' })
    await page.screenshot({ path: '/tmp/api-client-body.png' })
    await expect(page.getByRole('button', { name: 'Send', exact: true })).toBeDisabled()
  } finally { await application.close(); rmSync(directory, { recursive: true, force: true }) }
})
