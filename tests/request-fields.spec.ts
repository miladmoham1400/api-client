import { launchDesktop } from './fixtures/desktop'
import { shutdown } from './fixtures/shutdown'
import { mkdtempSync, rmSync } from 'node:fs'
import { tmpdir } from 'node:os'
import { join } from 'node:path'
import { expect, test } from '@playwright/test'

test('keyboard row editing preserves duplicate/disabled/order and validated settings after restart', async () => {
  const directory = mkdtempSync(join(tmpdir(), 'api-client-fields-ui-'))
  const env = { ...Object.fromEntries(Object.entries(process.env).filter((entry): entry is [string, string] => entry[1] !== undefined && !['ELECTRON_RUN_AS_NODE', 'ELECTRON_RENDERER_URL'].includes(entry[0]))), XDG_CONFIG_HOME: directory, APPDATA: directory }
  let application = await launchDesktop({ args: ['.'], chromiumSandbox: true, env })
  try {
    let page = await application.firstWindow()
    await page.getByRole('button', { name: 'Create Workspace', exact: true }).click()
    const dialog = page.getByRole('dialog', { name: 'Create workspace', exact: true })
    await dialog.getByLabel('Workspace name').fill('Fields workspace')
    await dialog.getByRole('button', { name: 'Create workspace', exact: true }).click()
    await expect(dialog).not.toBeVisible()
    await page.getByRole('button', { name: 'Create Request', exact: true }).click()
    await page.getByLabel('Request name', { exact: true }).fill('Fields')
    await page.getByRole('button', { name: 'Add param', exact: true }).focus()
    await page.keyboard.press('Enter')
    await page.getByLabel('Param 1 key', { exact: true }).focus()
    await page.keyboard.type('duplicate')
    await page.keyboard.press('Tab')
    await expect(page.getByLabel('Param 1 value', { exact: true })).toBeFocused()
    await page.keyboard.type('first')
    await page.getByRole('button', { name: 'Add param', exact: true }).click()
    await page.getByLabel('Param 2 key', { exact: true }).fill('duplicate')
    await page.getByLabel('Param 2 value', { exact: true }).fill('second')
    await page.getByLabel('Param 2 enabled', { exact: true }).focus()
    await page.keyboard.press('Space')
    await expect(page.getByLabel('Param 2 enabled', { exact: true })).not.toBeChecked()
    await page.getByRole('button', { name: 'Move param 2 up', exact: true }).click()
    await expect(page.getByLabel('Param 1 value', { exact: true })).toHaveValue('second')
    await expect(page.getByLabel('Param 1 enabled', { exact: true })).not.toBeChecked()
    await page.getByRole('button', { name: 'Add param', exact: true }).click()
    await page.getByLabel('Param 3 key', { exact: true }).fill('remove')
    await page.getByRole('button', { name: 'Remove param 3', exact: true }).click()
    await expect(page.getByRole('group', { name: /^Param row/ })).toHaveCount(2)
    await page.getByRole('tab', { name: 'Headers', exact: true }).first().click()
    await page.getByRole('button', { name: 'Add header', exact: true }).click()
    await page.getByLabel('Header 1 key', { exact: true }).fill('X-Fixture')
    await page.getByLabel('Header 1 value', { exact: true }).fill('saved disabled value')
    await page.getByLabel('Header 1 enabled', { exact: true }).uncheck()
    await page.getByRole('tab', { name: 'Settings', exact: true }).click()
    await expect(page.getByLabel('Follow redirects', { exact: true })).not.toBeChecked()
    await page.getByLabel('Overall timeout (ms)', { exact: true }).fill('99')
    await page.keyboard.press('Control+s')
    await expect(page.locator('#timeout-error')).toContainText('timeoutMs:')
    await expect(page.getByLabel('Overall timeout (ms)', { exact: true })).toHaveAttribute('aria-invalid', 'true')
    await page.getByLabel('Overall timeout (ms)', { exact: true }).fill('300001')
    await page.getByRole('button', { name: 'Save', exact: true }).click()
    await expect(page.locator('#timeout-error')).toContainText('300,000')
    await page.getByLabel('Overall timeout (ms)', { exact: true }).fill('12345')
    await page.getByLabel('Follow redirects', { exact: true }).focus()
    await page.keyboard.press('Space')
    await page.keyboard.press('Control+s')
    await expect(page.getByRole('status').filter({ hasText: /^Saved$/ })).toBeVisible()
    const workspace = await page.evaluate(() => window.offlineApi.workspaces.list())
    if (!workspace.ok || !workspace.data.selectedWorkspaceId) throw new Error('Missing workspace')
    const id = workspace.data.selectedWorkspaceId
    const saved = await page.evaluate(workspace => window.offlineApi.requests.list(workspace), id)
    if (!saved.ok || !saved.data.editor) throw new Error('Missing editor')
    expect(saved.data.editor.queryRows.map(row => [row.key, row.value, row.enabled])).toEqual([['duplicate', 'second', false], ['duplicate', 'first', true]])
    expect(saved.data.editor.headerRows[0]?.enabled).toBe(false)
    await page.getByRole('tab', { name: 'Params', exact: true }).click()
    await page.getByLabel('Param 1 value', { exact: true }).fill('unsaved')
    expect(await page.evaluate(workspace => window.offlineApi.requests.list(workspace), id)).toEqual(saved)
    await page.getByRole('button', { name: 'Discard edits', exact: true }).click()
    await expect(page.getByLabel('Param 1 value', { exact: true })).toHaveValue('second')
    await page.screenshot({ path: '/tmp/api-client-request-fields.png' })
    await application.close()
    application = await launchDesktop({ args: ['.'], chromiumSandbox: true, env })
    page = await application.firstWindow()
    await expect(page.getByLabel('Param 1 value', { exact: true })).toHaveValue('second')
    await expect(page.getByLabel('Param 1 enabled', { exact: true })).not.toBeChecked()
    expect(await page.evaluate(workspace => window.offlineApi.requests.list(workspace), id)).toEqual(saved)
    await page.getByRole('tab', { name: 'Headers', exact: true }).first().click()
    await expect(page.getByLabel('Header 1 value', { exact: true })).toHaveValue('saved disabled value')
    await expect(page.getByLabel('Header 1 enabled', { exact: true })).not.toBeChecked()
    await page.getByRole('tab', { name: 'Settings', exact: true }).click()
    await expect(page.getByLabel('Overall timeout (ms)', { exact: true })).toHaveValue('12345')
    await expect(page.getByLabel('Follow redirects', { exact: true })).toBeChecked()
    await expect(page.getByRole('button', { name: 'Send', exact: true })).toBeDisabled()
  } finally { await shutdown(application); rmSync(directory, { recursive: true, force: true }) }
})
