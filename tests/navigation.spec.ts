function environment(directory: string) {
  return { ...Object.fromEntries(Object.entries(process.env).filter((entry): entry is [string, string] => entry[1] !== undefined && !['ELECTRON_RUN_AS_NODE', 'ELECTRON_RENDERER_URL'].includes(entry[0]))), XDG_CONFIG_HOME: directory, APPDATA: directory }
}
async function workspace(page: Page, name: string) {
  await page.getByRole('button', { name: 'Create Workspace', exact: true }).click()
  const dialog = page.getByRole('dialog', { name: 'Create workspace', exact: true })
  await dialog.getByLabel('Workspace name').fill(name)
  await dialog.getByRole('button', { name: 'Create workspace', exact: true }).click()
  await expect(dialog).not.toBeVisible()
  const result = await page.evaluate(() => window.offlineApi.workspaces.list())
  if (!result.ok || !result.data.selectedWorkspaceId) throw new Error('Missing workspace')
  return result.data.selectedWorkspaceId
}
async function request(page: Page, name: string, url: string) {
  await page.getByRole('button', { name: 'Create Request', exact: true }).click()
  await page.getByLabel('Request name', { exact: true }).fill(name)
  await page.getByLabel('Request URL', { exact: true }).fill(url)
  await page.getByRole('button', { name: 'Save', exact: true }).click()
  await expect(page.getByRole('status').filter({ hasText: /^Saved$/ })).toBeVisible()
}

