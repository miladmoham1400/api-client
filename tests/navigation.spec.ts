test('cancel-and-navigate waits for an attempt still preparing before an execution ID exists', async () => {
  const directory = mkdtempSync(join(tmpdir(), 'api-client-navigation-preparing-')), fixture = await startFixture()
  const application = await launchDesktop({ args: ['.'], chromiumSandbox: true, env: environment(directory) })
  try {
    const page = await application.firstWindow(), a = await workspace(page, 'Preparing')
    await request(page, 'Hold', fixture.url + '/hold')
    const environments = await page.evaluate(w => window.offlineApi.environments.list(w), a)
    await application.evaluate(({ ipcMain }, snapshot) => {
      ipcMain.removeHandler('environments:list')
      ipcMain.handle('environments:list', () => new Promise(resolve => { Reflect.set(globalThis, 'releaseEnvironmentFixture', () => resolve(snapshot)) }))
    }, environments)
    await page.getByRole('button', { name: 'Send', exact: true }).click()
    await expect(page.getByRole('status').filter({ hasText: /^Preparing request/ })).toBeVisible()
    await page.getByRole('button', { name: 'Create Request', exact: true }).click()
    await page.getByRole('dialog', { name: 'Request in progress', exact: true }).getByRole('button', { name: 'Cancel request', exact: true }).click()
    await expect(page.getByLabel('Request name', { exact: true })).toHaveValue('Hold')
    await application.evaluate(() => {
      const release: unknown = Reflect.get(globalThis, 'releaseEnvironmentFixture')
      if (typeof release !== 'function') throw new Error('Missing preparation fixture')
      release()
    })
    await expect(page.getByLabel('Request name', { exact: true })).toHaveValue('New request')
    expect(await page.evaluate(w => window.offlineApi.requests.list(w), a)).toMatchObject({ ok: true, data: { requests: [expect.objectContaining({ name: 'Hold' })], editor: { name: 'Hold' } } })
    await expect.poll(() => new Promise<number>((resolve, reject) => fixture.server.getConnections((error, count) => error ? reject(error) : resolve(count)))).toBe(0)
    await page.getByRole('group', { name: 'Request: Hold', exact: true }).getByRole('button', { name: 'Hold', exact: true }).click()
    await page.getByRole('dialog', { name: 'Unsaved request changes' }).getByRole('button', { name: 'Discard', exact: true }).click()
    await expect(page.getByLabel('Request name', { exact: true })).toHaveValue('Hold')
    await page.getByRole('button', { name: 'Send', exact: true }).click()
    await expect(page.getByRole('status').filter({ hasText: /^Preparing request/ })).toBeVisible()
    await page.getByRole('button', { name: 'Workspace menu', exact: true }).click()
    await page.getByRole('menuitem', { name: 'Delete workspace', exact: true }).click()
    const confirmation = page.getByRole('dialog', { name: 'Delete workspace', exact: true })
    await confirmation.getByRole('button', { name: 'Delete permanently', exact: true }).click()
    await page.getByRole('dialog', { name: 'Request in progress', exact: true }).getByRole('button', { name: 'Cancel request', exact: true }).click()
    await confirmation.getByRole('button', { name: 'Cancel', exact: true }).click()
    await expect(confirmation).not.toBeVisible()
    await application.evaluate(() => {
      const release: unknown = Reflect.get(globalThis, 'releaseEnvironmentFixture')
      if (typeof release !== 'function') throw new Error('Missing preparation fixture')
      release()
    })
    await expect(page.getByRole('status').filter({ hasText: /^Request cancelled$/ })).toBeVisible()
    await expect(page.getByLabel('Request name', { exact: true })).toHaveValue('Hold')
    expect(await page.evaluate(() => window.offlineApi.workspaces.list())).toMatchObject({ ok: true, data: { selectedWorkspaceId: a, workspaces: [expect.objectContaining({ id: a })] } })
  } finally { await shutdown(application); await fixture.close(); rmSync(directory, { recursive: true, force: true }) }
})
