import { mkdtempSync, rmSync } from 'node:fs'
import { tmpdir } from 'node:os'
import { join } from 'node:path'
import { _electron, expect, test } from '@playwright/test'

test('two-workspace environments and variables preserve scope, masking, selection and restart state', async () => {
  const directory = mkdtempSync(join(tmpdir(), 'api-client-variable-ui-'))
  const env = { ...Object.fromEntries(Object.entries(process.env).filter((entry): entry is [string, string] => entry[1] !== undefined && !['ELECTRON_RUN_AS_NODE', 'ELECTRON_RENDERER_URL'].includes(entry[0]))), XDG_CONFIG_HOME: directory, APPDATA: directory }
  let application = await _electron.launch({ args: ['.'], chromiumSandbox: true, env })
  try {
    let page = await application.firstWindow()
    async function workspace(name: string) {
      await page.getByRole('button', { name: 'Create Workspace', exact: true }).click()
      const dialog = page.getByRole('dialog', { name: 'Create workspace', exact: true })
      await dialog.getByLabel('Workspace name').fill(name)
      await dialog.getByRole('button', { name: 'Create workspace', exact: true }).click()
      await expect(dialog).not.toBeVisible()
    }
    async function add(key: string, value: string, sensitive = false) {
      await page.getByLabel('Variable key', { exact: true }).fill(key)
      await page.getByLabel('Variable value', { exact: true }).fill(value)
      await page.getByLabel('Sensitive variable', { exact: true }).setChecked(sensitive)
      await page.getByRole('button', { name: 'Add variable', exact: true }).click()
      await expect(page.getByLabel('Variable key', { exact: true })).toHaveValue('')
    }
    await workspace('A')
    const a = (await page.getByLabel('Workspace', { exact: true }).inputValue())
    await page.getByRole('button', { name: 'Variables', exact: true }).click()
    const panel = page.getByRole('dialog', { name: 'Environments and variables' })
    await expect(panel).toBeVisible()
    await add('host', 'workspace-A')
    await add('fixture', 'synthetic-sensitive-ui', true)
    const secret = page.getByRole('group', { name: 'Variable fixture', exact: true })
    await expect(secret).toContainText('••••••••')
    await expect(secret).not.toContainText('synthetic-sensitive-ui')
    await page.getByRole('button', { name: 'Reveal fixture', exact: true }).click()
    await expect(secret).toContainText('synthetic-sensitive-ui')
    await page.getByRole('button', { name: 'Hide fixture', exact: true }).click()
    await expect(secret).not.toContainText('synthetic-sensitive-ui')
    await page.getByLabel('Variable key', { exact: true }).fill('host')
    await page.getByLabel('Variable value', { exact: true }).fill('duplicate')
    await page.getByRole('button', { name: 'Add variable', exact: true }).click()
    await expect(panel.getByRole('alert')).toContainText('duplicate keys')
    await page.getByRole('button', { name: 'Clear variable editor', exact: true }).click()
    await page.getByLabel('Environment name', { exact: true }).fill('Local')
    await page.getByRole('button', { name: 'Create environment', exact: true }).click()
    await page.getByLabel('Managed environment', { exact: true }).selectOption({ label: 'Local' })
    await page.getByLabel('Environment name', { exact: true }).fill('Renamed Local')
    await page.getByRole('button', { name: 'Rename selected environment', exact: true }).click()
    await page.getByLabel('Variable scope', { exact: true }).selectOption({ label: 'Selected environment: Renamed Local' })
    await add('host', '')
    await expect(panel.getByText('host: — Selected environment', { exact: true })).toBeVisible()
    await page.getByRole('button', { name: 'Close variables', exact: true }).click()
    await expect(page.getByRole('button', { name: 'Variables', exact: true })).toBeFocused()
    await workspace('B')
    const b = await page.getByLabel('Workspace', { exact: true }).inputValue()
    await expect(page.getByLabel('Environment', { exact: true })).toHaveValue('')
    await page.getByRole('button', { name: 'Variables', exact: true }).click()
    await expect(panel).toContainText('No variables in this scope.')
    await add('host', 'workspace-B')
    await page.getByRole('button', { name: 'Close variables', exact: true }).click()
    await page.getByLabel('Workspace', { exact: true }).selectOption(a)
    await expect(page.getByLabel('Environment', { exact: true })).toHaveValue(/.+/)
    const selected = await page.getByLabel('Environment', { exact: true }).inputValue()
    await application.close()
    application = await _electron.launch({ args: ['.'], chromiumSandbox: true, env })
    page = await application.firstWindow()
    await expect(page.getByLabel('Workspace', { exact: true })).toHaveValue(a)
    await expect(page.getByLabel('Environment', { exact: true })).toHaveValue(selected)
    await page.getByRole('button', { name: 'Variables', exact: true }).click()
    const result = await page.evaluate(w => window.offlineApi.variables.list(w, null), a)
    if (!result.ok) throw new Error('Missing variables')
    const fixture = result.data.items.find(v => v.key === 'fixture')
    if (!fixture?.isSensitive) throw new Error('Missing sensitive fixture')
    if (fixture.storageMode === 'session') {
      await expect(page.getByRole('group', { name: 'Variable fixture', exact: true })).toContainText('Missing sensitive value')
      await page.getByRole('button', { name: 'Re-enter fixture', exact: true }).click()
      await expect(page.getByLabel('Variable value', { exact: true })).toHaveValue('')
      await page.getByLabel('Variable value', { exact: true }).fill('synthetic-reentered')
      await page.getByRole('button', { name: 'Save variable', exact: true }).click()
      await expect(page.getByRole('button', { name: 'Reveal fixture', exact: true })).toBeEnabled()
    } else {
      await page.getByRole('button', { name: 'Reveal fixture', exact: true }).click()
      await expect(page.getByRole('group', { name: 'Variable fixture', exact: true })).toContainText('synthetic-sensitive-ui')
      await page.getByRole('button', { name: 'Hide fixture', exact: true }).click()
    }
    await page.getByRole('button', { name: 'Delete selected environment', exact: true }).click()
    await page.getByRole('button', { name: 'Confirm environment deletion', exact: true }).click()
    await expect(page.getByLabel('Managed environment', { exact: true })).toHaveValue('')
    await page.screenshot({ path: '/tmp/api-client-variables.png' })
    await page.getByRole('button', { name: 'Close variables', exact: true }).click()
    await page.getByLabel('Workspace', { exact: true }).selectOption(b)
    await page.getByRole('button', { name: 'Variables', exact: true }).click()
    await expect(page.getByRole('group', { name: 'Variable host', exact: true })).toContainText('workspace-B')
    await expect(page.getByRole('group', { name: 'Variable fixture', exact: true })).toHaveCount(0)
  } finally { await application.close(); rmSync(directory, { recursive: true, force: true }) }
})
